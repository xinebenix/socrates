/**
 * The string tables.
 *
 * `en` is the source of truth for *shape*: the `Dict` type is derived from it, so a key
 * added in English and forgotten in Chinese fails `tsc` rather than rendering blank in
 * production. That is why these are typed tables rather than JSON loaded at runtime.
 *
 * PROVENANCE. Most of the Chinese is lifted from the `Socrates zh-CN.dc.html` design
 * comp character for character. It has a deliberate literary register — 此番不中 for a
 * wrong answer, not 错误 — and paraphrasing it would flatten the voice the comp exists
 * to carry. The comp only drew the seven main screens, so strings it never showed
 * (most of the spend panel, several error and empty states) were translated against
 * those pairs as a style guide. Where the two disagree, the comp wins.
 *
 * CURRENCY stays in US dollars in both locales. The comp shows ¥, but the figures come
 * from Anthropic API billing and are dollars; rendering an unconverted number behind a
 * ¥ sign would state an amount that is simply false. A real redenomination needs a rate
 * and a rounding rule, which is a product decision rather than a translation.
 */

