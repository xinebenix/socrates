const DICTIONARIES: Record<Locale, Dict> = { en, zh };

export function dictionaryFor(locale: Locale): Dict {
  return DICTIONARIES[locale] ?? DICTIONARIES[DEFAULT_LOCALE];
}

/**
 * Fill `{name}` placeholders.
 *
 * Deliberately tolerant: an unknown placeholder is left as written rather than becoming
 * "undefined", so a mismatch between a template and its arguments shows up as visible
 * braces a reader can report instead of a confident lie.
 */
export function fill(template: string, values: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in values ? String(values[name]) : whole
  );
}
